CREATE TABLE order_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES work_orders(id),
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT valid_history_from CHECK (from_status IS NULL OR from_status IN ('PENDING','IN_PROGRESS','COMPLETED','DELIVERED')),
    CONSTRAINT valid_history_to CHECK (to_status IN ('PENDING','IN_PROGRESS','COMPLETED','DELIVERED'))
);
CREATE INDEX idx_history_order ON order_history(order_id, id);

-- Las órdenes de la primera entrega solo podían estar pendientes.
-- Conservamos su fecha de creación como registro inicial.
INSERT INTO order_history (order_id, from_status, to_status, changed_at)
SELECT id, NULL, status, created_at FROM work_orders;
