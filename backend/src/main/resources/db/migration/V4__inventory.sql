CREATE TABLE materials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 unit VARCHAR(10) NOT NULL CHECK (unit IN ('UNIDAD','KG','METRO','LITRO')),
 stock NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (stock >= 0)
);
CREATE TABLE stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 material_id BIGINT NOT NULL REFERENCES materials(id),
 order_id BIGINT REFERENCES work_orders(id),
 kind VARCHAR(10) NOT NULL CHECK (kind IN ('ENTRY','CONSUME')),
 quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
 reason VARCHAR(250) NOT NULL,
 actor_username VARCHAR(40) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK ((kind = 'ENTRY' AND order_id IS NULL) OR (kind = 'CONSUME' AND order_id IS NOT NULL))
);
CREATE INDEX idx_movements_material ON stock_movements(material_id,id);
